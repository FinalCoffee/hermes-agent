CREATE TABLE c_schema_migration (
    version     integer      NOT NULL,
    name        varchar(120) NOT NULL,
    checksum    char(64)     NOT NULL,
    applied_at  timestamptz  NOT NULL DEFAULT clock_timestamp(),
    applied_by  varchar(64)  NOT NULL DEFAULT current_user,
    CONSTRAINT c_schema_migration_pk PRIMARY KEY (version),
    CONSTRAINT c_schema_migration_uk_name UNIQUE (name),
    CONSTRAINT c_schema_migration_chk_version CHECK (version >= 1),
    CONSTRAINT c_schema_migration_chk_checksum CHECK (checksum ~ '^[0-9a-f]{64}$')
);
COMMENT ON TABLE c_schema_migration IS
    'One row = one migration file applied to this schema. checksum is the SHA-256 of the file, so an edited file is noticed. Append-only.';
CREATE TRIGGER c_schema_migration_append_only BEFORE UPDATE OR DELETE ON c_schema_migration
    FOR EACH ROW EXECUTE FUNCTION c_guard_append_only();

-- ---------------------------------------------------------------------------------------------
-- o_booking: the order header
-- ---------------------------------------------------------------------------------------------

CREATE TABLE o_booking (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    booking_code     varchar(14)   NOT NULL,
    buyer_channel    varchar(32)   NOT NULL,
    buyer_ref        varchar(128)  NOT NULL,
    chat_ref         varchar(128),
    contact_name     varchar(200),
    contact_email    varchar(320),
    contact_phone    varchar(32),
    erased_at        timestamptz,
    locale_code      varchar(16)   NOT NULL,
    currency         char(3)       NOT NULL,
    status           varchar(30)   NOT NULL DEFAULT 'DRAFT',
    total_amount     numeric(18,2) NOT NULL DEFAULT 0,
    idempotency_key  varchar(240),
    request_sha256   char(64),
    version          bigint        NOT NULL DEFAULT 1,
    created_by       varchar(64),
    created_dt       timestamptz   NOT NULL DEFAULT now(),
    updated_by       varchar(64),
    updated_dt       timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT o_booking_pk PRIMARY KEY (id),
    CONSTRAINT o_booking_uk_code UNIQUE (booking_code),
    CONSTRAINT o_booking_uk_id_currency UNIQUE (id, currency),
    CONSTRAINT o_booking_uk_idem UNIQUE (idempotency_key),
    CONSTRAINT o_booking_chk_code CHECK (booking_code ~ '^AC[0-9A-HJKMNP-TV-Z]{12}$'),
    CONSTRAINT o_booking_chk_channel CHECK (buyer_channel ~ '^[a-z][a-z0-9_]{0,31}$'),
    CONSTRAINT o_booking_chk_buyer_ref CHECK (buyer_ref <> ''),
    CONSTRAINT o_booking_chk_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT o_booking_chk_status CHECK (status IN (
        'DRAFT', 'PENDING_PAYMENT', 'CONFIRMED', 'PARTIALLY_CANCELLED', 'CANCELLED', 'COMPLETED',
        'FAILED', 'EXPIRED')),
    CONSTRAINT o_booking_chk_total CHECK (total_amount >= 0),
    CONSTRAINT o_booking_chk_request_sha CHECK (request_sha256 IS NULL OR request_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT o_booking_chk_idem CHECK ((idempotency_key IS NULL) = (request_sha256 IS NULL)),
    CONSTRAINT o_booking_chk_erased CHECK (
        erased_at IS NULL OR (contact_name IS NULL AND contact_email IS NULL AND contact_phone IS NULL
            AND chat_ref IS NULL AND idempotency_key IS NULL AND buyer_ref = 'erased:' || booking_code))
);
COMMENT ON TABLE o_booking IS
    'One row = one order placed through the bot, with at least one item. One currency per booking; total_amount equals the sum of its items'' sell_amount at COMMIT (o_booking_money). Who bought it, its code and its currency never change (o_booking_identity_guard). The contact columns and the buyer''s account and chat ids are personal data: erasing replaces buyer_ref with ''erased:<booking_code>'', clears the rest, and is final. created_by, updated_by and the event log''s actor name a component of the bot, never a person. Never deleted.';
COMMENT ON COLUMN o_booking.booking_code IS
    '''AC'' + 12 Crockford base32 characters (60 random bits) generated by the application; never derived from id.';
COMMENT ON COLUMN o_booking.buyer_channel IS 'Where the buyer talks to the bot, e.g. telegram.';
COMMENT ON COLUMN o_booking.buyer_ref IS
    'The buyer''s account id on that channel, as set by the gateway for the turn. Never taken from model output.';
COMMENT ON COLUMN o_booking.status IS
    'DRAFT, PENDING_PAYMENT, CONFIRMED, PARTIALLY_CANCELLED, CANCELLED, COMPLETED, FAILED, EXPIRED. Moved by the application with a conditional UPDATE on the old status and version.';
COMMENT ON COLUMN o_booking.idempotency_key IS
    'Server-namespaced: <buyer_channel>:<buyer_ref>:<client key>; the channel and the client key hold no colon. The same key with the same request_sha256 is a replay; with another it is a conflict.';
COMMENT ON COLUMN o_booking.request_sha256 IS
    'SHA-256 of everything the creating request asked for (currency, contact, every item with its detail and travellers). Set exactly when idempotency_key is.';

CREATE INDEX o_booking_idx_buyer ON o_booking (buyer_channel, buyer_ref, created_dt DESC);
CREATE INDEX o_booking_idx_pending ON o_booking (created_dt) WHERE status = 'PENDING_PAYMENT';
CREATE TRIGGER o_booking_touch BEFORE UPDATE ON o_booking
    FOR EACH ROW EXECUTE FUNCTION c_touch_updated_dt();
CREATE TRIGGER o_booking_no_delete BEFORE DELETE ON o_booking
    FOR EACH ROW EXECUTE FUNCTION c_guard_no_delete();

CREATE FUNCTION o_booking_check_identity() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    v_erasing boolean := OLD.erased_at IS NULL AND NEW.erased_at IS NOT NULL;
BEGIN
    IF (NEW.id, NEW.booking_code, NEW.buyer_channel, NEW.currency, NEW.locale_code, NEW.created_dt)
       IS DISTINCT FROM
       (OLD.id, OLD.booking_code, OLD.buyer_channel, OLD.currency, OLD.locale_code, OLD.created_dt) THEN
        RAISE EXCEPTION 'o_booking %: its code, channel, currency and locale are immutable', OLD.id
            USING ERRCODE = '23514';
    END IF;
    IF OLD.erased_at IS NOT NULL AND NEW.erased_at IS DISTINCT FROM OLD.erased_at THEN
        RAISE EXCEPTION 'o_booking %: erasure is final', OLD.id USING ERRCODE = '23514';
    END IF;
    IF NOT v_erasing AND (NEW.buyer_ref, NEW.chat_ref, NEW.idempotency_key, NEW.request_sha256)
       IS DISTINCT FROM (OLD.buyer_ref, OLD.chat_ref, OLD.idempotency_key, OLD.request_sha256) THEN
        RAISE EXCEPTION 'o_booking %: its buyer and request key change only when it is erased', OLD.id
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER o_booking_identity_guard BEFORE UPDATE ON o_booking
    FOR EACH ROW EXECUTE FUNCTION o_booking_check_identity();

