COMMENT ON TABLE o_supplier_request IS
    'One row = one attempt to place, pay or cancel an item at its supplier. Written NEW in a short transaction and committed BEFORE the supplier is called; the result (PLACED, FAILED, or UNKNOWN when there was no clear answer) is written afterwards in another. At most one NEW or UNKNOWN row per item and kind (o_supplier_request_uk_live): an UNKNOWN attempt is settled by reading the supplier, never by sending again. At most one PLACED row per item and kind (o_supplier_request_uk_placed): an item is placed, paid or cancelled once. Request and response bodies are never stored, only their SHA-256, because they carry traveller data.';
COMMENT ON COLUMN o_supplier_request.client_request_key IS
    'Sent to the supplier as the idempotency key: ac:item:<item id>:<kind>:<attempt>.';
COMMENT ON COLUMN o_supplier_request.result_code IS 'A short machine code for the outcome; never supplier free text.';

CREATE UNIQUE INDEX o_supplier_request_uk_live ON o_supplier_request (item_id, request_kind)
    WHERE state IN ('NEW', 'UNKNOWN');
CREATE UNIQUE INDEX o_supplier_request_uk_placed ON o_supplier_request (item_id, request_kind)
    WHERE state = 'PLACED';
CREATE INDEX o_supplier_request_idx_supplier_order ON o_supplier_request (source_code, supplier_order_no)
    WHERE supplier_order_no IS NOT NULL;
