-- Accomy bot order store: simulated orders, and the exchange rates that price them in US dollars.
--
-- A simulated order is recorded like any other order, with its items confirmed and no supplier
-- request, so the data says plainly that no supplier was contacted. Its amounts are US dollars. A
-- supplier price in another currency is converted with a rate from c_fx_rate, and the item keeps
-- the supplier's amount and the rate, so the conversion is a fact that never changes. Modelled on
-- hashtrip's c_fx_rate (lib/db/ddl/00_m0_foundation.sql, T08), without its currency table.

-- ---------------------------------------------------------------------------------------------
-- c_fx_rate: exchange-rate snapshots (append-only)
-- ---------------------------------------------------------------------------------------------

CREATE TABLE c_fx_rate (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    base_currency   char(3)        NOT NULL,
    quote_currency  char(3)        NOT NULL,
    rate            numeric(20,10) NOT NULL,
    as_of           timestamptz    NOT NULL,
    provider_code   varchar(32)    NOT NULL,
    created_dt      timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT c_fx_rate_pk PRIMARY KEY (id),
    CONSTRAINT c_fx_rate_uk_id_pair UNIQUE (id, base_currency, quote_currency),
    CONSTRAINT c_fx_rate_uk_pair_asof UNIQUE (base_currency, quote_currency, provider_code, as_of),
    CONSTRAINT c_fx_rate_chk_base CHECK (base_currency ~ '^[A-Z]{3}$'),
    CONSTRAINT c_fx_rate_chk_quote CHECK (quote_currency ~ '^[A-Z]{3}$'),
    CONSTRAINT c_fx_rate_chk_pair CHECK (base_currency <> quote_currency),
    CONSTRAINT c_fx_rate_chk_rate CHECK (rate > 0),
    CONSTRAINT c_fx_rate_chk_provider CHECK (provider_code ~ '^[a-z][a-z0-9_-]{0,31}$')
);
COMMENT ON TABLE c_fx_rate IS
    'One row = the rates one provider quoted at one instant for one currency pair. rate is what one unit of base_currency bought in quote_currency. Items keep the row they were converted at (o_booking_item.fx_rate_id), so the conversion is an immutable fact. A corrected rate is a new row with a new as_of. Append-only.';
COMMENT ON COLUMN c_fx_rate.rate IS
    'Units of quote_currency for one unit of base_currency, numeric(20,10). Not rounded: the amount someone pays is rounded up to the minor unit by the application.';
COMMENT ON COLUMN c_fx_rate.provider_code IS 'Who quoted the rate, e.g. a fixed demo table or a bank feed. A free identifier, not a closed list.';
CREATE TRIGGER c_fx_rate_append_only BEFORE UPDATE OR DELETE ON c_fx_rate
    FOR EACH ROW EXECUTE FUNCTION c_guard_append_only();
CREATE TRIGGER c_fx_rate_no_truncate BEFORE TRUNCATE ON c_fx_rate
    FOR EACH STATEMENT EXECUTE FUNCTION c_guard_no_truncate();

-- ---------------------------------------------------------------------------------------------
-- o_booking.order_mode: a simulated order has no supplier behind it
-- ---------------------------------------------------------------------------------------------

ALTER TABLE o_booking
    ADD COLUMN order_mode varchar(12) NOT NULL DEFAULT 'SUPPLIER',
    ADD CONSTRAINT o_booking_chk_order_mode CHECK (order_mode IN ('SUPPLIER', 'SIMULATED'));
COMMENT ON COLUMN o_booking.order_mode IS
    'SUPPLIER: the items are placed with their suppliers. SIMULATED: a demonstration order, confirmed in the bot only; its items are NOT_APPLICABLE and no supplier request is ever written for it. Set at creation and never changed (o_booking_identity_guard).';
CREATE INDEX o_booking_idx_simulated_created ON o_booking (created_dt) WHERE order_mode = 'SIMULATED';

CREATE OR REPLACE FUNCTION o_booking_check_identity() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    v_erasing boolean := OLD.erased_at IS NULL AND NEW.erased_at IS NOT NULL;
BEGIN
    IF (NEW.id, NEW.booking_code, NEW.buyer_channel, NEW.currency, NEW.locale_code, NEW.created_dt, NEW.order_mode)
       IS DISTINCT FROM
       (OLD.id, OLD.booking_code, OLD.buyer_channel, OLD.currency, OLD.locale_code, OLD.created_dt, OLD.order_mode) THEN
        RAISE EXCEPTION 'o_booking %: its code, channel, currency, locale and order mode are immutable', OLD.id
            USING ERRCODE = '23514';
    END IF;
    IF OLD.erased_at IS NOT NULL AND NEW.erased_at IS DISTINCT FROM OLD.erased_at THEN
        RAISE EXCEPTION 'o_booking %: erasure is final', OLD.id USING ERRCODE = '23514';
    END IF;
    IF NOT v_erasing AND (NEW.buyer_ref, NEW.chat_ref, NEW.idempotency_key, NEW.request_sha256)
       IS DISTINCT FROM (OLD.buyer_ref, OLD.chat_ref, OLD.idempotency_key, OLD.request_sha256) THEN
        RAISE EXCEPTION 'o_booking %: its buyer and request key change only when it is erased', OLD.id
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;

-- ---------------------------------------------------------------------------------------------
-- o_booking_item: the supplier's price and the rate it was converted at
-- ---------------------------------------------------------------------------------------------

ALTER TABLE o_booking_item
    ADD COLUMN source_currency char(3),
    ADD COLUMN source_amount numeric(18,4),
    ADD COLUMN fx_rate_id bigint,
    ADD CONSTRAINT o_booking_item_chk_fx_all_or_none CHECK (
        (source_currency IS NULL AND source_amount IS NULL AND fx_rate_id IS NULL)
        OR (source_currency IS NOT NULL AND source_amount IS NOT NULL AND fx_rate_id IS NOT NULL)),
    ADD CONSTRAINT o_booking_item_chk_source_currency CHECK (
        source_currency IS NULL OR (source_currency ~ '^[A-Z]{3}$' AND source_currency <> currency)),
    ADD CONSTRAINT o_booking_item_chk_source_amount CHECK (source_amount IS NULL OR source_amount >= 0),
    ADD CONSTRAINT o_booking_item_fk_fx FOREIGN KEY (fx_rate_id, source_currency, currency)
        REFERENCES c_fx_rate (id, base_currency, quote_currency);
CREATE INDEX o_booking_item_idx_fx_rate ON o_booking_item (fx_rate_id) WHERE fx_rate_id IS NOT NULL;
COMMENT ON COLUMN o_booking_item.source_currency IS
    'The currency the supplier priced the item in, when it differs from the booking currency. All three conversion columns are set together or not at all.';
COMMENT ON COLUMN o_booking_item.source_amount IS 'The supplier''s amount in source_currency, before conversion.';
COMMENT ON COLUMN o_booking_item.fx_rate_id IS
    'The c_fx_rate row the conversion used: its base is source_currency and its quote is the item''s currency (composite foreign key).';

CREATE OR REPLACE FUNCTION o_booking_item_check_identity() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF (NEW.id, NEW.booking_id, NEW.item_seq, NEW.item_kind, NEW.source_code, NEW.title_snapshot,
        NEW.quantity, NEW.currency, NEW.sell_amount, NEW.placed_at,
        NEW.source_currency, NEW.source_amount, NEW.fx_rate_id)
       IS DISTINCT FROM
       (OLD.id, OLD.booking_id, OLD.item_seq, OLD.item_kind, OLD.source_code, OLD.title_snapshot,
        OLD.quantity, OLD.currency, OLD.sell_amount, OLD.placed_at,
        OLD.source_currency, OLD.source_amount, OLD.fx_rate_id) THEN
        RAISE EXCEPTION 'o_booking_item %: what was bought and what it cost are immutable', OLD.id
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;

-- ---------------------------------------------------------------------------------------------
-- A simulated order is never sent to a supplier
-- ---------------------------------------------------------------------------------------------

CREATE FUNCTION o_supplier_request_check_simulated() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM o_booking_item i JOIN o_booking b ON b.id = i.booking_id
               WHERE i.id = NEW.item_id AND b.order_mode = 'SIMULATED') THEN
        RAISE EXCEPTION 'o_supplier_request: item % is a simulated order and has no supplier', NEW.item_id
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER o_supplier_request_simulated_guard BEFORE INSERT ON o_supplier_request
    FOR EACH ROW EXECUTE FUNCTION o_supplier_request_check_simulated();
