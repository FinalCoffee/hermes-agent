-- Accomy bot order store: who the customer is, and the trip an order belongs to.
--
--   o_customer  1 ── n  o_trip  1 ── n  o_booking  1 ── n  o_booking_item (hotel, flight or event)
--
-- A customer is found by Telegram account id or by email. A trip is the master record of one journey:
-- the orders a customer places for it, on one day or over several, are its details. Every booking
-- belongs to one customer and one of that customer's trips.

-- ---------------------------------------------------------------------------------------------
-- o_customer
-- ---------------------------------------------------------------------------------------------

CREATE TABLE o_customer (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    telegram_user_id  varchar(32),
    email             varchar(320),
    display_name      varchar(200),
    phone             varchar(32),
    locale_code       varchar(16),
    erased_at         timestamptz,
    version           bigint       NOT NULL DEFAULT 1,
    created_by        varchar(64),
    created_dt        timestamptz  NOT NULL DEFAULT now(),
    updated_by        varchar(64),
    updated_dt        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT o_customer_pk PRIMARY KEY (id),
    CONSTRAINT o_customer_chk_telegram CHECK (telegram_user_id IS NULL OR telegram_user_id ~ '^-?[0-9]{1,20}$'),
    CONSTRAINT o_customer_chk_email CHECK (email IS NULL OR email ~ '^[^@[:space:]]+@[^@[:space:]]+$'),
    CONSTRAINT o_customer_chk_identified CHECK (
        erased_at IS NOT NULL OR telegram_user_id IS NOT NULL OR email IS NOT NULL),
    CONSTRAINT o_customer_chk_erased CHECK (
        erased_at IS NULL OR (telegram_user_id IS NULL AND email IS NULL AND display_name IS NULL AND phone IS NULL))
);
COMMENT ON TABLE o_customer IS
    'One row = one person who orders through the bot, known by a Telegram account id, an email address, or both. A Telegram id names at most one customer (o_customer_uk_telegram). An email identifies a customer only when there is no Telegram account (o_customer_uk_email_only); Telegram customers may share one, so an email finds customers but does not identify one. Every column but the keys is personal data: erasing clears it for good and keeps the row, so the customer''s trips and orders stay linked to an anonymous customer. Never deleted.';
COMMENT ON COLUMN o_customer.telegram_user_id IS
    'The Telegram account id the gateway bound to the turn that ordered. Never taken from model output.';
COMMENT ON COLUMN o_customer.email IS 'The contact email given with an order. Compared without regard to case.';

CREATE UNIQUE INDEX o_customer_uk_telegram ON o_customer (telegram_user_id) WHERE telegram_user_id IS NOT NULL;
-- A customer known only by email is identified by it; with a Telegram account, the email is contact data.
CREATE UNIQUE INDEX o_customer_uk_email_only ON o_customer (lower(email))
    WHERE telegram_user_id IS NULL AND email IS NOT NULL;
CREATE INDEX o_customer_idx_email ON o_customer (lower(email)) WHERE email IS NOT NULL;
CREATE TRIGGER o_customer_touch BEFORE UPDATE ON o_customer
    FOR EACH ROW EXECUTE FUNCTION c_touch_updated_dt();
CREATE TRIGGER o_customer_no_delete BEFORE DELETE ON o_customer
    FOR EACH ROW EXECUTE FUNCTION c_guard_no_delete();
CREATE TRIGGER o_customer_no_truncate BEFORE TRUNCATE ON o_customer
    FOR EACH STATEMENT EXECUTE FUNCTION c_guard_no_truncate();

CREATE FUNCTION o_customer_check_identity() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF OLD.erased_at IS NOT NULL AND NEW.erased_at IS DISTINCT FROM OLD.erased_at THEN
        RAISE EXCEPTION 'o_customer %: erasure is final', OLD.id USING ERRCODE = '23514';
    END IF;
    IF OLD.telegram_user_id IS NOT NULL AND NEW.telegram_user_id IS DISTINCT FROM OLD.telegram_user_id
       AND NEW.erased_at IS NULL THEN
        RAISE EXCEPTION 'o_customer %: its Telegram account changes only when it is erased', OLD.id
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER o_customer_identity_guard BEFORE UPDATE ON o_customer
    FOR EACH ROW EXECUTE FUNCTION o_customer_check_identity();

-- ---------------------------------------------------------------------------------------------
-- o_trip
-- ---------------------------------------------------------------------------------------------

CREATE TABLE o_trip (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    trip_code    varchar(14)  NOT NULL,
    customer_id  bigint       NOT NULL,
    title        varchar(200) NOT NULL,
    starts_on    date,
    ends_on      date,
    status       varchar(12)  NOT NULL DEFAULT 'ACTIVE',
    version      bigint       NOT NULL DEFAULT 1,
    created_by   varchar(64),
    created_dt   timestamptz  NOT NULL DEFAULT now(),
    updated_by   varchar(64),
    updated_dt   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT o_trip_pk PRIMARY KEY (id),
    CONSTRAINT o_trip_uk_code UNIQUE (trip_code),
    CONSTRAINT o_trip_uk_id_customer UNIQUE (id, customer_id),
    CONSTRAINT o_trip_fk_customer FOREIGN KEY (customer_id) REFERENCES o_customer (id),
    CONSTRAINT o_trip_chk_code CHECK (trip_code ~ '^TR[0-9A-HJKMNP-TV-Z]{12}$'),
    CONSTRAINT o_trip_chk_title CHECK (title <> ''),
    CONSTRAINT o_trip_chk_dates CHECK (starts_on IS NULL OR ends_on IS NULL OR ends_on >= starts_on),
    CONSTRAINT o_trip_chk_status CHECK (status IN ('ACTIVE', 'COMPLETED', 'CANCELLED'))
);
COMMENT ON TABLE o_trip IS
    'One row = one journey of one customer: the master record its bookings hang from. starts_on and ends_on span the stays, flights and events booked for it so far and widen as bookings are added; a background tracker can read them to follow the trip. The title is the customer''s or the bot''s name for the trip and is cleared when the customer is erased. Never deleted.';
COMMENT ON COLUMN o_trip.trip_code IS '''TR'' + 12 Crockford base32 characters generated by the application.';
COMMENT ON COLUMN o_trip.status IS
    'ACTIVE, COMPLETED or CANCELLED. A booking is added only to an ACTIVE trip. Cancelling a trip''s last order cancels the trip; nothing sets COMPLETED yet (a tracker will, after ends_on).';

CREATE INDEX o_trip_idx_customer ON o_trip (customer_id, created_dt DESC);
CREATE TRIGGER o_trip_touch BEFORE UPDATE ON o_trip
    FOR EACH ROW EXECUTE FUNCTION c_touch_updated_dt();
CREATE TRIGGER o_trip_no_delete BEFORE DELETE ON o_trip
    FOR EACH ROW EXECUTE FUNCTION c_guard_no_delete();
CREATE TRIGGER o_trip_no_truncate BEFORE TRUNCATE ON o_trip
    FOR EACH STATEMENT EXECUTE FUNCTION c_guard_no_truncate();

CREATE FUNCTION o_trip_check_identity() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF (NEW.id, NEW.trip_code, NEW.customer_id, NEW.created_dt)
       IS DISTINCT FROM (OLD.id, OLD.trip_code, OLD.customer_id, OLD.created_dt) THEN
        RAISE EXCEPTION 'o_trip %: its code and its customer are immutable', OLD.id USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER o_trip_identity_guard BEFORE UPDATE ON o_trip
    FOR EACH ROW EXECUTE FUNCTION o_trip_check_identity();

-- ---------------------------------------------------------------------------------------------
-- o_booking: its customer and its trip
-- ---------------------------------------------------------------------------------------------

-- NOT NULL without a default: the migration refuses to run on a database that already holds bookings
-- with no customer, rather than inventing one for them.
ALTER TABLE o_booking
    ADD COLUMN customer_id bigint NOT NULL,
    ADD COLUMN trip_id bigint NOT NULL,
    ADD CONSTRAINT o_booking_fk_customer FOREIGN KEY (customer_id) REFERENCES o_customer (id),
    ADD CONSTRAINT o_booking_fk_trip FOREIGN KEY (trip_id, customer_id) REFERENCES o_trip (id, customer_id);
COMMENT ON COLUMN o_booking.customer_id IS 'Who ordered. Set at creation and never changed (o_booking_identity_guard).';
COMMENT ON COLUMN o_booking.trip_id IS
    'The trip this order is a detail of; it is one of the same customer''s trips (composite foreign key). Set at creation and never changed.';
CREATE INDEX o_booking_idx_customer ON o_booking (customer_id, created_dt DESC);
CREATE INDEX o_booking_idx_trip ON o_booking (trip_id, created_dt);

CREATE OR REPLACE FUNCTION o_booking_check_identity() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    v_erasing boolean := OLD.erased_at IS NULL AND NEW.erased_at IS NOT NULL;
BEGIN
    IF (NEW.id, NEW.booking_code, NEW.buyer_channel, NEW.currency, NEW.locale_code, NEW.created_dt, NEW.order_mode,
        NEW.customer_id, NEW.trip_id)
       IS DISTINCT FROM
       (OLD.id, OLD.booking_code, OLD.buyer_channel, OLD.currency, OLD.locale_code, OLD.created_dt, OLD.order_mode,
        OLD.customer_id, OLD.trip_id) THEN
        RAISE EXCEPTION 'o_booking %: its code, channel, currency, locale, order mode, customer and trip are immutable',
            OLD.id USING ERRCODE = '23514';
    END IF;
    IF OLD.erased_at IS NOT NULL AND NEW.erased_at IS DISTINCT FROM OLD.erased_at THEN
        RAISE EXCEPTION 'o_booking %: erasure is final', OLD.id USING ERRCODE = '23514';
    END IF;
    IF NOT v_erasing AND (NEW.buyer_ref, NEW.chat_ref, NEW.idempotency_key, NEW.request_sha256)
       IS DISTINCT FROM (OLD.buyer_ref, OLD.chat_ref, OLD.idempotency_key, OLD.request_sha256) THEN
        RAISE EXCEPTION 'o_booking %: its buyer and request key change only when it is erased', OLD.id
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;

-- An erased customer has no order that still names them.
CREATE FUNCTION o_customer_check_erased() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM o_booking WHERE customer_id = NEW.id AND erased_at IS NULL) THEN
        RAISE EXCEPTION 'o_customer %: erased while one of their bookings is not', NEW.id USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER o_customer_erased AFTER UPDATE OF erased_at ON o_customer
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW WHEN (NEW.erased_at IS NOT NULL)
    EXECUTE FUNCTION o_customer_check_erased();
