CREATE FUNCTION o_booking_check_money() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    v_booking_id bigint;
    v_total numeric(18,2);
    v_sum numeric(18,2);
BEGIN
    IF TG_TABLE_NAME = 'o_booking' THEN
        v_booking_id := NEW.id;
    ELSE
        v_booking_id := NEW.booking_id;
    END IF;
    SELECT total_amount INTO v_total FROM o_booking WHERE id = v_booking_id;
    SELECT sum(sell_amount) INTO v_sum FROM o_booking_item WHERE booking_id = v_booking_id;
    IF v_sum IS NULL THEN
        RAISE EXCEPTION 'o_booking %: a booking needs at least one item', v_booking_id USING ERRCODE = '23514';
    END IF;
    IF v_total IS DISTINCT FROM v_sum THEN
        RAISE EXCEPTION 'o_booking %: total_amount % is not the sum of its items %', v_booking_id, v_total, v_sum
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER o_booking_money AFTER INSERT OR UPDATE OF total_amount ON o_booking
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION o_booking_check_money();
CREATE CONSTRAINT TRIGGER o_booking_item_money AFTER INSERT ON o_booking_item
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION o_booking_check_money();

CREATE FUNCTION o_booking_item_check_subtype() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    v_found boolean;
BEGIN
    CASE NEW.item_kind
        WHEN 'HOTEL' THEN
            SELECT EXISTS (SELECT 1 FROM o_booking_item_hotel WHERE item_id = NEW.id) INTO v_found;
        WHEN 'FLIGHT' THEN
            SELECT EXISTS (SELECT 1 FROM o_booking_item_flight_segment WHERE item_id = NEW.id) INTO v_found;
        WHEN 'EVENT_TICKET' THEN
            SELECT EXISTS (SELECT 1 FROM o_booking_item_event WHERE item_id = NEW.id) INTO v_found;
    END CASE;
    IF NOT v_found THEN
        RAISE EXCEPTION 'o_booking_item %: % item has no detail row', NEW.id, NEW.item_kind USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER o_booking_item_subtype AFTER INSERT ON o_booking_item
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION o_booking_item_check_subtype();

CREATE FUNCTION o_booking_check_erased() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM o_booking_item_traveller t JOIN o_booking_item i ON i.id = t.item_id
               WHERE i.booking_id = NEW.id AND t.erased_at IS NULL) THEN
        RAISE EXCEPTION 'o_booking %: erased while a traveller is not', NEW.id USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER o_booking_erased AFTER UPDATE OF erased_at ON o_booking
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW WHEN (NEW.erased_at IS NOT NULL)
    EXECUTE FUNCTION o_booking_check_erased();

-- Row triggers do not fire on TRUNCATE. These stop an application mistake; the role that owns the
-- tables can still drop any trigger, so the application should not connect as the owner in production.
DO $$
DECLARE
    v_table text;
BEGIN
    FOREACH v_table IN ARRAY ARRAY[
        'c_schema_migration', 'o_booking', 'o_booking_item', 'o_booking_item_hotel', 'o_booking_item_flight',
        'o_booking_item_flight_segment', 'o_booking_item_event', 'o_booking_item_traveller',
        'o_supplier_request', 'o_booking_event']
    LOOP
        EXECUTE format('CREATE TRIGGER %I BEFORE TRUNCATE ON %I FOR EACH STATEMENT EXECUTE FUNCTION c_guard_no_truncate()',
                       v_table || '_no_truncate', v_table);
    END LOOP;
END $$;
