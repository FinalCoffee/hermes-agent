CREATE FUNCTION o_booking_item_traveller_check() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF EXISTS (SELECT 1 FROM o_booking b JOIN o_booking_item i ON i.booking_id = b.id
                   WHERE i.id = NEW.item_id AND b.erased_at IS NOT NULL) THEN
            RAISE EXCEPTION 'o_booking_item %: its booking is erased and takes no traveller', NEW.item_id
                USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END IF;
    IF (NEW.item_id, NEW.traveller_seq, NEW.traveller_kind)
       IS DISTINCT FROM (OLD.item_id, OLD.traveller_seq, OLD.traveller_kind) THEN
        RAISE EXCEPTION 'o_booking_item_traveller: a traveller stays on its item' USING ERRCODE = '23514';
    END IF;
    IF OLD.erased_at IS NOT NULL AND NEW.erased_at IS DISTINCT FROM OLD.erased_at THEN
        RAISE EXCEPTION 'o_booking_item_traveller: erasure is final' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER o_booking_item_traveller_guard BEFORE INSERT OR UPDATE ON o_booking_item_traveller
    FOR EACH ROW EXECUTE FUNCTION o_booking_item_traveller_check();

