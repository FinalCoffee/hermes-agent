-- Accomy bot order store: baseline.
--
-- Modelled on hashtrip's order core (lib/db/ddl/04_m4_booking.sql and docs/hashtrip-schema.md §1, §8):
-- bigint identity keys, status as varchar + CHECK on separate axes, numeric(18,2) money with one
-- currency per booking, version columns for optimistic locking, no deletes (retire by status),
-- personal data erased in place, and a supplier request log that stores hashes, never bodies.
-- Left out because the bot holds no stock of its own and has no back office: stock holds, schedule
-- version chains, price lines, coupons, payments, mail, and every vishnu legacy table.
--
-- Names are unqualified: the runner sets search_path to the store's schema. One transaction, applied
-- once; the runner records it in c_schema_migration.

-- ---------------------------------------------------------------------------------------------
-- Shared trigger functions
-- ---------------------------------------------------------------------------------------------

CREATE FUNCTION c_touch_updated_dt() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    NEW.updated_dt := clock_timestamp();
    RETURN NEW;
END $$;

CREATE FUNCTION c_guard_append_only() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    RAISE EXCEPTION '% is append-only', TG_TABLE_NAME USING ERRCODE = '42501';
END $$;

CREATE FUNCTION c_guard_no_delete() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    RAISE EXCEPTION '% rows are never deleted: retire by status', TG_TABLE_NAME USING ERRCODE = '23514';
END $$;

CREATE FUNCTION c_guard_no_truncate() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    RAISE EXCEPTION '% is never truncated', TG_TABLE_NAME USING ERRCODE = '42501';
END $$;

