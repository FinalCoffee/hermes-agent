    'Where the supplier order stands: NOT_APPLICABLE, NOT_SENT, SENT, CONFIRMED_BY_SUPPLIER, REJECTED, UNKNOWN, CANCEL_SENT, CANCELLED_BY_SUPPLIER. UNKNOWN means a supplier write had no clear answer and must be reconciled by reading the supplier, never by sending it again.';
